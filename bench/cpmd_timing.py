#!/usr/bin/env python3
"""Cost of CPMD's routines per evaluation between two of its timing tables.

With CPMDC_TIPRI_EVERY=N libcpmdc prints CPMD's timing table after every
N-th evaluation, with the times summed from the first evaluation of the
process.  For each output this takes the last two tables, divides the change
in the calls and in the average total time of each routine by the evaluations
between them, which the calls of embed_scf count, and writes an Org table
with the calls and the seconds of each run.  The rows are --routines, or
without it embed_scf and the --rows routines after it with the most total
time per evaluation in the first run.

usage: cpmd_timing.py NAME=OUTPUT [NAME=OUTPUT ...] [--routines R,R,...]
                      [--rows 12] [--output FILE]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

EVALUATION = "embed_scf"
ROW = re.compile(r"^ (\S+)\s+(\d+)\s+[\d.]+\s+[\d.]+\s+([\d.]+)\s+[\d.]+\s*$")


def tables(text: str) -> list[dict[str, tuple[int, float]]]:
    found: list[dict[str, tuple[int, float]]] = []
    rows = None
    for line in text.splitlines():
        if line.startswith(" SUBROUTINE") and "SELF TIME" in line:
            rows = {}
            found.append(rows)
        elif rows is not None:
            if match := ROW.match(line):
                rows[match.group(1)] = (int(match.group(2)), float(match.group(3)))
            elif line.startswith(" *") and rows:
                rows = None
    return found


def per_evaluation(path: Path) -> tuple[int, dict[str, tuple[float, float]]]:
    found = tables(path.read_text(encoding="utf-8", errors="replace"))
    if len(found) < 2:
        raise SystemExit(f"{path}: {len(found)} timing table(s); the cost needs two")
    before, after = found[-2], found[-1]
    evaluations = after.get(EVALUATION, (0, 0.0))[0] - before.get(EVALUATION, (0, 0.0))[0]
    if evaluations <= 0:
        raise SystemExit(f"{path}: no {EVALUATION} calls between the last two tables")
    cost = {}
    for name, (calls, total) in after.items():
        calls0, total0 = before.get(name, (0, 0.0))
        cost[name] = ((calls - calls0) / evaluations, (total - total0) / evaluations)
    return evaluations, cost


def report(runs: list[tuple[str, Path]], routines: list[str] | None, rows: int) -> str:
    costs = [(name, path, *per_evaluation(path)) for name, path in runs]
    first = costs[0][3]
    if routines is None:
        ranked = sorted((name for name in first if name != EVALUATION), key=lambda name: -first[name][1])
        routines = [EVALUATION, *ranked[:rows]]
    header = "| Routine |" + "".join(f" {name} calls | {name}, s |" for name, *_ in costs)
    lines = ["# Generated by bench/cpmd_timing.py; do not edit by hand.",
             "# Per evaluation between the last two timing tables of " + ", ".join(
                 f"{name} ({path.name}, {evaluations} evaluation{'s' * (evaluations != 1)})"
                 for name, path, evaluations, _ in costs),
             "", header, "|" + "+".join("-" * len(cell) for cell in header.strip("|").split("|")) + "|"]
    for routine in routines:
        cells = []
        for *_, cost in costs:
            calls, seconds = cost.get(routine, (0.0, 0.0))
            cells += [f"{calls:.1f}", f"{seconds:.3f}"]
        lines.append(f"| {routine} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("runs", nargs="+", metavar="NAME=OUTPUT")
    parser.add_argument("--routines", type=lambda text: text.split(","))
    parser.add_argument("--rows", type=int, default=12)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    runs = []
    for run in args.runs:
        name, sep, path = run.partition("=")
        if not sep or not name or not path:
            parser.error(f"{run}: expected NAME=OUTPUT")
        runs.append((name, Path(path)))
    text = report(runs, args.routines, args.rows)
    if args.output:
        args.output.write_text(text, encoding="utf-8")
    print(text, end="")


if __name__ == "__main__":
    main()
